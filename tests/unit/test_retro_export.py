def _inputs(report=None, **kwargs):
    return build_retro_export_inputs(report if report is not None else _report(), **kwargs)


class TestExportInputs:
    def test_timestamps_are_captured_once_and_agree(self):
        inputs = _inputs()
        # Both stamps come from one datetime.now(); the date must be the ts's
        # own day, or a document could carry a footer from the day before.
        assert inputs["generated_ts"].startswith(inputs["generated_date"])

    def test_inputs_are_plain_json(self):
        # The json round-trip is what makes the wire params byte-identical to
        # what a stored report deserializes from — tuples become lists here.
        inputs = _inputs()
        assert inputs == __import__("json").loads(__import__("json").dumps(inputs))
        assert isinstance(inputs["report"]["cards"], list)
        assert inputs["report"]["cards"][1]["reactions"] == [["👍", 3], ["🔥", 1]]

    def test_editable_flag_travels(self):
        assert _inputs(editable=True)["editable"] is True
        assert _inputs()["editable"] is False

    def test_history_rows_travel_verbatim(self):
        history = _history(("2026-07-10", 3), ("2026-06-26", 8))
        assert _inputs(history=history)["history"] == history


class TestReferenceImplementation:
    def test_round_trip_reproduces_the_document(self):
        # The reference implementation rebuilds through the store deserializer;
        # what it renders must match rendering the report directly.
        report = _report()
        result = build_retro_export(_inputs(report))
        assert result["markdown"].splitlines()[0] == build_retro_markdown(report).splitlines()[0]
        assert result["args"]["report"]["kind"] == "retro"

    def test_pinned_timestamps_make_the_document_a_golden(self):
        inputs = {**_inputs(), "generated_ts": "2026-07-10 09:30", "generated_date": "2026-07-10"}
        first = build_retro_export(inputs)
        assert first == build_retro_export(inputs)  # deterministic, byte for byte
        assert "· 2026-07-10 09:30_" in first["markdown"]
        assert first["args"]["footer"] == "Generated by yeaboi.ai • 2026-07-10"

    def test_annotations_reach_the_payload(self):
        report = RetroReport(
            date="2026-07-10",
            annotations=(Annotation(kind="note", text="the deploy was rolled back", author="Rae"),),
        )
        result = build_retro_export(_inputs(report))
        assert result["args"]["report"]["annotations"][0]["text"] == "the deploy was rolled back"
        assert "the deploy was rolled back" in result["markdown"]

    def test_result_carries_the_contract_version(self):
        from yeaboi.gocore.client import CONTRACT_VERSION

        assert build_retro_export(_inputs())["contract_version"] == CONTRACT_VERSION

    def test_key_order_is_contractual(self):
        # `args` is json.dumps-ed into the page boot payload, so key order is
        # part of the wire, not a detail of this dict.
        result = build_retro_export(_inputs())
        assert list(result) == ["contract_version", "markdown", "args"]
        assert list(result["args"]["report"]) == ["kind", "columns", "participants", "carried", "trend"]


class TestGoDispatch:
    """retro.build_export dispatch: Go results win; any failure → Python."""

    def test_no_client_means_python_path(self, monkeypatch):
        monkeypatch.setattr("yeaboi.gocore.get_client", lambda: None)
        assert go_build_retro_export(_inputs()) is None

    def test_client_construction_failure_returns_none(self, monkeypatch):
        def boom():
            raise RuntimeError("discovery exploded")

        monkeypatch.setattr("yeaboi.gocore.get_client", boom)
        assert go_build_retro_export(_inputs()) is None

    def test_core_error_returns_none_for_fallback(self, monkeypatch):
        from yeaboi.gocore import CoreError

        class BrokenClient:
            def request(self, *args, **kwargs):
                raise CoreError("sidecar exploded")

        monkeypatch.setattr("yeaboi.gocore.get_client", lambda: BrokenClient())
        assert go_build_retro_export(_inputs()) is None

    def test_empty_markdown_is_malformed(self, monkeypatch):
        canned = build_retro_export(_inputs())

        class FakeClient:
            def request(self, method, params, on_progress=None, timeout=None):
                return {**canned, "markdown": ""}

        monkeypatch.setattr("yeaboi.gocore.get_client", lambda: FakeClient())
        assert go_build_retro_export(_inputs()) is None

    def test_wrong_report_kind_is_malformed(self, monkeypatch):
        canned = build_retro_export(_inputs())
        wrong = {**canned, "args": {**canned["args"], "report": {**canned["args"]["report"], "kind": "poker"}}}

        class FakeClient:
            def request(self, method, params, on_progress=None, timeout=None):
                return wrong

        monkeypatch.setattr("yeaboi.gocore.get_client", lambda: FakeClient())
        assert go_build_retro_export(_inputs()) is None

    def test_short_column_list_is_malformed(self, monkeypatch):
        # Every grid ships, including the empty ones — a short list would draw
        # a board missing a column.
        canned = build_retro_export(_inputs())
        report = {**canned["args"]["report"], "columns": canned["args"]["report"]["columns"][:2]}

        class FakeClient:
            def request(self, method, params, on_progress=None, timeout=None):
                return {**canned, "args": {**canned["args"], "report": report}}

        monkeypatch.setattr("yeaboi.gocore.get_client", lambda: FakeClient())
        assert go_build_retro_export(_inputs()) is None

    def test_carried_count_mismatch_is_malformed(self, monkeypatch):
        inputs = _inputs(_report_with_carried())
        canned = build_retro_export(inputs)
        report = {**canned["args"]["report"], "carried": canned["args"]["report"]["carried"][:1]}

        class FakeClient:
            def request(self, method, params, on_progress=None, timeout=None):
                return {**canned, "args": {**canned["args"], "report": report}}

        monkeypatch.setattr("yeaboi.gocore.get_client", lambda: FakeClient())
        assert go_build_retro_export(inputs) is None

    def test_good_results_are_returned_verbatim(self, monkeypatch, caplog):
        canned = build_retro_export(_inputs())

        class FakeClient:
            def request(self, method, params, on_progress=None, timeout=None):
                assert method == "retro.build_export"
                return canned

        monkeypatch.setattr("yeaboi.gocore.get_client", lambda: FakeClient())
        with caplog.at_level(logging.INFO, logger="yeaboi.retro.export"):
            assert go_build_retro_export(_inputs()) == canned
        assert "retro.build_export served by the sidecar" in caplog.text

    def test_the_page_renders_from_a_sidecar_document(self, monkeypatch):
        # The seam's whole point: a served document draws the same page.
        canned = build_retro_export(_inputs())

        class FakeClient:
            def request(self, method, params, on_progress=None, timeout=None):
                return canned

        monkeypatch.setattr("yeaboi.gocore.get_client", lambda: FakeClient())
        html = build_retro_html(_report())
        assert island(html)["report"]["columns"] == canned["args"]["report"]["columns"]

    def test_export_falls_back_without_a_sidecar(self, tmp_path, monkeypatch):
        # The Python path stays complete: no binary, both artifacts still written.
        target = tmp_path / "demo"
        monkeypatch.setattr("yeaboi.gocore.get_client", lambda: None)

        def _fake_dir(key):
            target.mkdir(parents=True, exist_ok=True)
            return target

        monkeypatch.setattr("yeaboi.paths.get_retro_export_dir", _fake_dir)
        paths = export_retro(_report(), project_name="Demo")
        assert paths["markdown"].read_text(encoding="utf-8").startswith("# Sprint Retro")
        assert "<!DOCTYPE html>" in paths["html"].read_text(encoding="utf-8")

    def test_both_artifacts_come_from_one_dispatch(self, tmp_path, monkeypatch):
        # One seam call per export — the .md and the .html can never disagree
        # about which side built them.
        calls = []
        target = tmp_path / "demo"

        def _counting(report, *, history=(), editable=False):
            calls.append(report)
            return build_retro_export(build_retro_export_inputs(report, history=history, editable=editable))

        monkeypatch.setattr(retro_export, "_export_doc", _counting)

        def _fake_dir(key):
            target.mkdir(parents=True, exist_ok=True)
            return target

        monkeypatch.setattr("yeaboi.paths.get_retro_export_dir", _fake_dir)
        export_retro(_report(), project_name="Demo")
        assert len(calls) == 1

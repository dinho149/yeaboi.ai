def _breadcrumbs(url: str, h1: str, lookup: dict) -> dict:
    """Breadcrumb trail from the nav tree, current page last and without a URL.

    The final item carries a ``name`` but no ``item``, which is Google's stated
    guidance for the page you are already on.
    """
    trail: list[tuple[str, str | None]] = [("Home", f"{SITE}/")]
    group_label, parent, _title = lookup.get(url, ("", None, h1))
    if url != "/docs/index.html":
        trail.append(("Docs", f"{SITE}/docs/index.html"))
    if parent:
        trail.append((lookup[parent][2], f"{SITE}{parent}"))
    elif group_label == "Modes" and url != "/docs/modes/index.html":
        trail.append(("Modes", f"{SITE}/docs/modes/index.html"))
    trail.append((h1, None))

    items = []
    for position, (name, item) in enumerate(trail, start=1):
        node: dict = {"@type": "ListItem", "position": position, "name": name}
        if item:
            node["item"] = item
        items.append(node)
    return {"@type": "BreadcrumbList", "@id": f"{SITE}{url}#breadcrumb", "itemListElement": items}


def _collection_items(url: str, groups: list[dict]) -> list[dict]:
    """ItemList for a hub page: its children, or every other page for /docs/."""
    if url == "/docs/modes/index.html":
        entries = [
            child
            for group in groups
            for entry in group["entries"]
            if entry["path"] == url
            for child in entry.get("children", ())
        ]
    else:
        entries = [entry for group in groups for entry in group["entries"] if entry["path"] != url]
    return [
        {"@type": "ListItem", "position": i, "name": e["title"], "url": f"{SITE}{e['path']}"}
        for i, e in enumerate(entries, start=1)
    ]



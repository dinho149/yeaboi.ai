def rel_of(path: Path) -> str:
    """Repo-relative posix key under ``docs/`` — the key used by KINDS."""
    return path.relative_to(DOCS).as_posix()


def url_for(path: Path) -> str:
    """Site-absolute URL for a repo path, applying the Pages strip rule.

    GitHub Pages serves ``docs/`` AS the domain root, so exactly one directory
    level disappears: ``docs/docs/modes/retro.html`` is served at
    ``/docs/modes/retro.html``. Only the site root index collapses to ``/``.

    Note ``docs/docs/index.html`` maps to ``/docs/index.html``, NOT ``/docs/``,
    even though both URLs resolve. Every path in ``NAV_GROUPS``, the hardcoded
    ``navigateTo("/docs/index.html", true)`` in ``buildRail``, and
    ``setDocsCurrent``'s string-equality check all use the explicit filename —
    canonicalising to the prettier form would disagree with every internal link
    on the site and break the current-page highlight. The canonical tag still
    consolidates the duplicate, which is the part that matters to a crawler.
    """
    rel = rel_of(path)
    return "/" if rel == "index.html" else "/" + rel


_TITLE_RE = re.compile(r"^<title>(.*)</title>\s*$", re.MULTILINE)
_DESC_RE = re.compile(r'^<meta name="description" content="(.*)" />\s*$', re.MULTILINE)
_H1_RE = re.compile(r"<h1[^>]*>(.*?)</h1>", re.DOTALL)
_TAGS_RE = re.compile(r"<[^>]+>")


def _text(raw: str) -> str:
    """Markup fragment to canonical plain text (entities resolved, tags gone)."""
    return html.unescape(_TAGS_RE.sub("", raw)).strip()


def page_copy(text: str, path: Path) -> tuple[str, str, str]:
    """Extract (title, description, h1) as canonical plain text.

    Raises rather than guessing: a page whose head does not match the shape
    every other page uses is a bug to fix, not something to paper over with a
    default that would then be silently wrong in a social card.
    """
    for name, pattern in (("<title>", _TITLE_RE), ("description", _DESC_RE), ("<h1>", _H1_RE)):
        if not pattern.search(text):
            msg = f"{rel_of(path)}: no single-line {name} found — cannot generate SEO tags"
            raise SystemExit(msg)
    title = _text(_TITLE_RE.search(text).group(1))
    desc = _text(_DESC_RE.search(text).group(1))
    h1 = _text(_H1_RE.search(text).group(1))
    return title, desc, h1


# ---------------------------------------------------------------------------
# NAV_GROUPS — read out of site.js, the single source of truth
# ---------------------------------------------------------------------------

_NAV_KEY_RE = re.compile(r"([{,]\s*)(label|entries|title|path|children)(\s*:)")


def parse_nav_groups(js: str) -> list[dict]:
    """Read the ``NAV_GROUPS`` array literal out of site.js as Python data.

    The literal is a strict JSON subset apart from unquoted keys and trailing
    commas, both of which are mechanical to fix. Sliced by brace depth rather
    than by regex so a nested ``children`` array can't terminate the match
    early. A malformed literal raises here at generation time — loud and
    immediate, which is the only acceptable failure mode for a parse like this.
    """
    start = js.index("var NAV_GROUPS = [") + js[js.index("var NAV_GROUPS = [") :].index("[")
    depth = 0
    for i, ch in enumerate(js[start:], start):
        if ch == "[":
            depth += 1
        elif ch == "]":
            depth -= 1
            if depth == 0:
                literal = js[start : i + 1]
                break
    else:  # pragma: no cover - unbalanced brackets in site.js
        msg = "NAV_GROUPS in site.js has unbalanced brackets"
        raise SystemExit(msg)

    quoted = _NAV_KEY_RE.sub(r'\1"\2"\3', literal)
    no_trailing = re.sub(r",(\s*[\]}])", r"\1", quoted)
    return json.loads(no_trailing)


def nav_lookup(groups: list[dict]) -> dict[str, tuple[str, str | None, str]]:
    """Map each nav path to ``(group_label, parent_path, title)``.

    ``parent_path`` is set only for pages nested under another entry's
    ``children`` — that is what produces the four-level breadcrumb for a mode
    page versus the three-level one for everything else.
    """
    out: dict[str, tuple[str, str | None, str]] = {}
    for group in groups:
        for entry in group["entries"]:
            out[entry["path"]] = (group["label"], None, entry["title"])
            for child in entry.get("children", ()):
                out[child["path"]] = (group["label"], entry["path"], child["title"])
    return out



# Anchored on full lines and on these three prefixes only. `description`,
# `theme-color`, `color-scheme` and `viewport` are load-bearing and must
# survive — a greedier pattern eating one of those is the worst realistic
# outcome of this whole change.
_STRAY_RE = re.compile(
    r'^[ \t]*<(?:meta property="og:|meta name="twitter:|link rel="canonical").*?>[ \t]*\n',
    re.MULTILINE,
)
_ASSET_V_RE = re.compile(r'((?:href|src)="/(?:docs/)?assets/[^"?]+\?v=)\d+(")')


def _splice(text: str, begin: str, end: str, block: str, anchor: str, *, after: bool) -> str:
    """Replace a sentinel block, or insert it next to ``anchor`` on first run."""
    if begin in text:
        pattern = re.compile(re.escape(begin) + r".*?" + re.escape(end), re.DOTALL)
        return pattern.sub(lambda _: block, text, count=1)
    if anchor not in text:
        msg = f"anchor {anchor!r} not found — cannot insert generated block"
        raise SystemExit(msg)
    if after:
        return text.replace(anchor, anchor + "\n" + block, 1)
    return text.replace(anchor, block + "\n" + anchor, 1)


def render(path: Path, groups: list[dict]) -> str:
    """The full desired contents of one HTML page."""
    text = path.read_text(encoding="utf-8")
    kind = KINDS[rel_of(path)]
    url = url_for(path)
    title, desc, h1 = page_copy(text, path)

    # Scrub hand-written og/twitter/canonical tags that the block now owns,
    # but only outside it, or re-running would eat its own output.
    if HEAD_BEGIN in text:
        head, sep, tail = text.partition(HEAD_BEGIN)
        body, sep2, rest = tail.partition(HEAD_END)
        text = _STRAY_RE.sub("", head) + sep + body + sep2 + _STRAY_RE.sub("", rest)
    else:
        text = _STRAY_RE.sub("", text)

    desc_line = _DESC_RE.search(text).group(0).rstrip("\n")
    text = _splice(text, HEAD_BEGIN, HEAD_END, head_block(kind, url, title, desc, h1, groups), desc_line, after=True)

    if kind is not Kind.LANDING and "</article>" in text:
        text = _splice(text, FOOT_BEGIN, FOOT_END, footer_block(url, groups), "</article>", after=True)

    text = _ASSET_V_RE.sub(rf"\g<1>{ASSET_VERSION}\g<2>", text)

    # LF, no trailing whitespace, exactly one final newline — or pre-commit's
    # hooks and this script rewrite each other forever.
    lines = [ln.rstrip() for ln in text.replace("\r\n", "\n").split("\n")]
    return "\n".join(lines).rstrip("\n") + "\n"


def render_sitemap(paths: list[Path]) -> str:
    """A <loc>-only sitemap. No lastmod/changefreq/priority — see the docstring."""
    urls = [url_for(p) for p in paths if KINDS[rel_of(p)] is not Kind.ERROR]
    body = "\n".join(f"  <url><loc>{SITE}{u}</loc></url>" for u in sorted(urls))
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        f"<!-- {_GENERATED_NOTE} -->\n"
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        f"{body}\n"
        "</urlset>\n"
    )


def render_robots() -> str:
    """robots.txt. No AI-crawler blocks: for an MIT dev tool, being quotable by
    assistants is distribution, not leakage — and that is a deliberate call.
    """
    return (
        f"# {_GENERATED_NOTE}\n"
        "User-agent: *\n"
        "Allow: /\n"
        "\n"
        "# Internal design docs, published by accident and now moved out of docs/.\n"
        "# Kept here for the window in which the old URLs are still cached.\n"
        "Disallow: /superpowers/\n"
        "# Orphan PDF carrying the superseded brand name; nothing links to it.\n"
        "Disallow: /ScrumTeamTraining.pdf\n"
        "\n"
        f"Sitemap: {SITE}/sitemap.xml\n"
    )


def pages() -> list[Path]:
    return sorted(DOCS.rglob("*.html"))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if any generated output is stale")
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(message)s")

    groups = parse_nav_groups(SITE_JS.read_text(encoding="utf-8"))
    found = {rel_of(p) for p in pages()}
    if missing := found - set(KINDS):
        msg = f"pages with no KINDS entry: {sorted(missing)} — add them to KINDS in {Path(__file__).name}"
        raise SystemExit(msg)

    wanted: dict[Path, str] = {p: render(p, groups) for p in pages()}
    wanted[DOCS / "sitemap.xml"] = render_sitemap(pages())
    wanted[DOCS / "robots.txt"] = render_robots()

    stale = [p for p, text in wanted.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        if stale:
            names = "\n  ".join(str(p.relative_to(ROOT)) for p in stale)
            logger.error("stale generated site output:\n  %s\n\nrun: make site-seo", names)
            return 1
        logger.info("✓ docs/ SEO output is up to date (%d pages)", len(pages()))
        return 0

    for path, text in wanted.items():
        if path in stale:
            path.write_text(text, encoding="utf-8")
    logger.info("✓ wrote %d file(s) across %d pages", len(stale), len(pages()))
    return 0


if __name__ == "__main__":
    sys.exit(main())

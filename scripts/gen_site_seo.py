def attr(value: str) -> str:
    """Escape for an HTML attribute value."""
    return html.escape(value, quote=True)


def json_ld(payload: dict) -> str:
    """Serialise JSON-LD so it cannot break out of its <script> element.

    Same rule as ``src/yeaboi/web/assets.py:json_island``: ``</script>`` inside
    a JSON string would end the element, so the three characters that could
    start a tag are escaped as JSON unicode escapes (still valid JSON, parses
    to the same string). U+2028/9 are legal in JSON but not in JS string
    literals, and break older parsers.
    """
    raw = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    for bad, good in (("<", "\\u003c"), (">", "\\u003e"), ("&", "\\u0026"), (" ", "\\u2028"), (" ", "\\u2029")):
        raw = raw.replace(bad, good)
    return raw



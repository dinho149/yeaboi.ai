def _ga_lines() -> list[str]:
    """The GA4 snippet, or nothing at all while the ID is a placeholder.

    Lives in ``<head>`` and not the body because ``navigateTo`` swaps
    ``#page-content`` via ``outerHTML``, and a script inserted that way never
    executes — a body snippet would run on hard loads only.

    Consent Mode v2 defaults to denied and ``client_storage:'none'`` means no
    cookie is ever written, so no consent banner is required. The trade is that
    GA4 reports cookieless pings: user and session counts become modelled
    rather than exact, which is the right price for a docs site whose question
    is "which pages get read".
    """
    if GA_MEASUREMENT_ID == GA_PLACEHOLDER or not GA_MEASUREMENT_ID:
        return [
            "<!-- Google Analytics 4: not configured yet. Set GA_MEASUREMENT_ID in",
            "     scripts/gen_site_seo.py and re-run `make site-seo`. Emitting nothing",
            "     rather than a placeholder ID keeps a dead tag off production. -->",
        ]
    gid = attr(GA_MEASUREMENT_ID)
    return [
        f"<!-- Google Analytics 4 ({gid}). In <head> because navigateTo() swaps",
        "     #page-content with outerHTML, so a body script would never execute after a",
        "     client-side nav. Cookieless (client_storage:'none'), so no consent banner is",
        "     required. NOTE: 'Page changes based on browser history events' must be OFF in",
        "     the GA4 stream, or the explicit page_view in site.js double-counts. -->",
        f'<script async src="https://www.googletagmanager.com/gtag/js?id={gid}"></script>',
        "<script>",
        "window.dataLayer=window.dataLayer||[];function gtag(){dataLayer.push(arguments);}",
        "gtag('consent','default',{ad_storage:'denied',ad_user_data:'denied',"
        "ad_personalization:'denied',analytics_storage:'denied'});",
        "gtag('js',new Date());",
        f"gtag('config','{gid}',{{client_storage:'none',ads_data_redaction:true}});",
        "</script>",
    ]


def head_block(kind: Kind, url: str, title: str, desc: str, h1: str, groups: list[dict]) -> str:
    """The managed ``<head>`` block for one page."""
    lines = [HEAD_BEGIN, f"<!-- {_GENERATED_NOTE} -->"]

    if kind is Kind.ERROR:
        # noindex so a 404 never enters the index, follow so its links still
        # pass a lost crawler on to real pages.
        lines.append('<meta name="robots" content="noindex, follow" />')
    else:
        lines += [
            f'<link rel="canonical" href="{SITE}{url}" />',
            '<meta name="robots" content="index, follow, max-image-preview:large, '
            'max-snippet:-1, max-video-preview:-1" />',
        ]

    if GSC_VERIFICATION:
        lines.append(f'<meta name="google-site-verification" content="{attr(GSC_VERIFICATION)}" />')

    og_type = "article" if kind is Kind.ARTICLE else "website"
    lines += [
        '<meta property="og:site_name" content="yeaboi" />',
        '<meta property="og:locale" content="en_US" />',
        f'<meta property="og:type" content="{og_type}" />',
        f'<meta property="og:title" content="{attr(title)}" />',
        f'<meta property="og:description" content="{attr(desc)}" />',
    ]
    if kind is not Kind.ERROR:
        lines.append(f'<meta property="og:url" content="{SITE}{url}" />')
    lines += [
        f'<meta property="og:image" content="{SITE}{OG_CARD}" />',
        f'<meta property="og:image:secure_url" content="{SITE}{OG_CARD}" />',
        '<meta property="og:image:type" content="image/png" />',
        f'<meta property="og:image:width" content="{OG_CARD_W}" />',
        f'<meta property="og:image:height" content="{OG_CARD_H}" />',
        f'<meta property="og:image:alt" content="{attr(OG_CARD_ALT)}" />',
        '<meta name="twitter:card" content="summary_large_image" />',
        f'<meta name="twitter:title" content="{attr(title)}" />',
        f'<meta name="twitter:description" content="{attr(desc)}" />',
        f'<meta name="twitter:image" content="{SITE}{OG_CARD}" />',
        f'<meta name="twitter:image:alt" content="{attr(OG_CARD_ALT)}" />',
    ]

    graph = build_graph(kind, url, title, desc, h1, groups)
    if graph:
        lines.append(f'<script type="application/ld+json">{json_ld(graph)}</script>')

    lines += _ga_lines()
    lines.append(HEAD_END)
    return "\n".join(lines)


def footer_block(url: str, groups: list[dict]) -> str:
    """A static, visible nav footer — the fix for zero crawlable docs links.

    Before this, a crawler fetching any docs page saw no link to any sibling:
    the rail dropdown is built by JS into ``.rail-menu-inner`` and
    ``.rail-menu`` is ``visibility:hidden`` until ``.expanded``, while
    ``<aside id="docs-sidebar">`` is ``display:none`` and nothing in site.js
    ever writes to it. 15 leaf pages were reachable only from two hubs.

    Emitted after ``</article>`` rather than inside it, because
    ``_buildDocsIndex()`` indexes ``.docs-content article`` for the client-side
    search — 17 link titles per page would swamp every query. And never with
    ``data-reveal``, which starts at ``opacity:0``: a crawlable nav must not
    depend on JS running.
    """
    out = [
        FOOT_BEGIN,
        f"<!-- {_GENERATED_NOTE} -->",
        '<footer class="docs-foot">',
        '  <nav class="docs-foot-cols" aria-label="Documentation">',
    ]
    for group in groups:
        out += [
            '    <div class="nav-group">',
            f'      <p class="nav-group-label">{attr(group["label"])}</p>',
            "      <ul>",
        ]
        for entry in group["entries"]:
            for path, title in [(entry["path"], entry["title"])] + [
                (c["path"], c["title"]) for c in entry.get("children", ())
            ]:
                cur = ' aria-current="page"' if path == url else ""
                out.append(f'        <li><a href="{path}"{cur}>{attr(title)}</a></li>')
        out += ["      </ul>", "    </div>"]
    out += [
        "  </nav>",
        '  <div class="docs-foot-meta">',
        '    <span><a href="/">yeaboi</a> — best friend to engineers and agents</span>',
        "    <span>MIT licensed</span>",
        f'    <a href="{REPO_URL}" rel="noopener">GitHub ↗</a>',
        f'    <a href="{PYPI_URL}" rel="noopener">PyPI ↗</a>',
        "  </div>",
        "</footer>",
        FOOT_END,
    ]
    return "\n".join(out)



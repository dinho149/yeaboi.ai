def export_retro(report: RetroReport, *, project_name: str = "", history: Sequence[dict] = ()) -> dict[str, Path]:
    """Write the retro as Markdown + HTML under the retro export dir.

    Returns ``{"markdown": Path, "html": Path}``. One file per day (dated
    filename) — a re-run the same day overwrites so the latest wins.
    ``history`` (RetroStore.get_history rows) feeds the HTML trend chart.
    """
    from yeaboi.html_theme import export_page
    from yeaboi.paths import get_retro_export_dir

    key = _slug(project_name or report.project_name or report.session_id)
    out_dir = get_retro_export_dir(key)
    stem = _stem(report)
    md_path = out_dir / f"{stem}.md"
    html_path = out_dir / f"{stem}.html"
    # One seam call renders both artifacts — the markdown and the HTML's args
    # come from the same dispatch, so the two files can never disagree about
    # which side (sidecar or Python) built them.
    doc = _export_doc(report, history=history)
    md_path.write_text(doc["markdown"], encoding="utf-8")
    html_path.write_text(export_page(**doc["args"], markdown_name=f"{stem}.md"), encoding="utf-8")
    logger.info("Retro exported: %s , %s", md_path, html_path)
    return {"markdown": md_path, "html": html_path}

# HTML
# ---------------------------------------------------------------------------


def _card_payload(card, *, editable: bool = False, list_field: str = "cards") -> dict:
    """One card as data: its text, who wrote it, and what the room did to it."""
    out: dict = {"text": card.text, "reactions": [[emoji, count] for emoji, count in card.reactions if count]}
    if editable and card.id:
        # Addressed by id, not by text — the text is the editable field, and a
        # key that moves when you edit it is not a key.
        anchor = row_anchor(list_field, "id", card.id)
        out["anchor"] = anchor
        out["edit"] = edit_map(anchor, card, ("text",))
    # A card the AI facilitator wrote is attributed as such, never to a person —
    # `origin` is the fact, and `author` on those rows is the literal "AI".
    if card.origin == "ai":
        out["ai"] = True
    elif card.author:
        out["author"] = card.author
    return out


def retro_export_args(
    report: RetroReport, *, history: Sequence[dict] = (), editable: bool = False, generated_date: str = ""
) -> dict[str, object]:
    """Return the chrome + payload keyword arguments for one retro document.

    See :func:`yeaboi.standup.export.standup_export_args` for why this is split
    out: an editable shared document rebuilds the payload without a page.
    ``generated_date`` pins the footer date (empty means "now") — the seam's
    only nondeterminism, hoisted by :func:`build_retro_export_inputs`.
    """
    from yeaboi.html_theme import trend

    by_grid = report.by_grid()
    # Every column, including the empty ones, in board order. Whether an empty
    # column gets a card or a footnote is a layout question, and layout is the
    # bundle's; sending only the filled ones would decide it here.
    columns = [
        {"grid": grid, "cards": [_card_payload(c, editable=editable) for c in by_grid.get(grid, [])]}
        for grid in RETRO_GRIDS
    ]

    args = dict(
        mode="retro",
        title=_title(report),
        wordmark="retro",
        facts=[
            ("DATE", report.date or ""),
            ("CARDS", str(len(report.cards))),
            ("PARTICIPANTS", str(len(report.participants))),
        ],
        report={
            "kind": "retro",
            "columns": columns,
            "participants": list(report.participants),
            "carried": [
                {
                    "status": c.status or "pending",
                    "text": c.text,
                    **(_card_payload(c, editable=True, list_field="carried_action_items") if editable else {}),
                }
                for c in report.carried_action_items
            ],
            "trend": trend(
                history,
                date_key="retro_date",
                value_key="card_count",
                title="Card volume trend",
                label="Card volume",
                cutoff_date=report.date,
                current=(report.date, len(report.cards)),
            ),
        },
        footer=f"Generated by yeaboi.ai • {generated_date or datetime.now().strftime('%Y-%m-%d')}",
    )
    return with_annotations(args, report)


def build_retro_html(report: RetroReport, *, history: Sequence[dict] = (), document_title: str = "") -> str:
    """Return the retro as a self-contained HTML document.

    ``history`` is optional ``RetroStore.get_history`` rows (newest-first); with
    two or more retros it powers the card-volume trend sparkline.
    """
    from yeaboi.html_theme import export_page

    doc = _export_doc(report, history=history)
    return export_page(
        **doc["args"],  # type: ignore[arg-type]
        markdown_name=f"{_stem(report)}.md",
        document_title=document_title,
    )


# ---------------------------------------------------------------------------
# The build-export seam — retro.build_export
# ---------------------------------------------------------------------------


def build_retro_export_inputs(report: RetroReport, *, history: Sequence[dict] = (), editable: bool = False) -> dict:
    """Freeze one retro document into the ``retro.build_export`` wire params.

    A single ``datetime.now()`` capture hoists the seam's only nondeterminism
    into the params, and the json round-trip freezes the report into the same
    plain-JSON shape a stored one takes — so the sidecar and the reference
    implementation see byte-identical inputs.
    """
    now = datetime.now()
    return json.loads(
        json.dumps(
            {
                "report": asdict(report),
                "history": list(history),
                "editable": bool(editable),
                "generated_ts": now.strftime("%Y-%m-%d %H:%M"),
                "generated_date": now.strftime("%Y-%m-%d"),
            }
        )
    )


def build_retro_export(inputs: dict) -> dict:
    """Python reference implementation of ``retro.build_export``.

    Rebuilds the report through the store deserializer — the same round-trip a
    stored report takes — then renders with the wire-pinned timestamps. Key
    order is contractual: ``args`` is json.dumps-ed into the page boot payload.
    """
    from yeaboi.gocore.client import CONTRACT_VERSION
    from yeaboi.retro.store import report_from_dict

    report = report_from_dict(inputs["report"])
    return {
        "contract_version": CONTRACT_VERSION,
        "markdown": build_retro_markdown(report, generated_ts=inputs["generated_ts"]),
        "args": retro_export_args(
            report,
            history=inputs["history"],
            editable=inputs["editable"],
            generated_date=inputs["generated_date"],
        ),
    }


# The exact top-level keyword set the callers splat into
# ``export_page(**args, markdown_name=...)``, which is keyword-only and rejects
# unknown names. Pinned here because a within-v1 binary skew that grows, drops,
# or renames a key would otherwise TypeError out of the export *after* the .md
# was written, instead of falling back to Python (the ``go_score_docs``
# key-set idiom; annotations ride inside ``report``, never at this level).
_RETRO_ARG_KEYS = frozenset({"mode", "title", "wordmark", "facts", "report", "footer"})


def _valid_retro_export(result: object, inputs: dict) -> bool:
    """Structural checks on a sidecar result — any failure means malformed → Python."""
    if not isinstance(result, dict):
        return False
    if not (isinstance(result.get("markdown"), str) and result["markdown"]):
        return False
    args = result.get("args")
    if not isinstance(args, dict) or set(args) != _RETRO_ARG_KEYS:
        return False
    report = args.get("report")
    if not isinstance(report, dict) or report.get("kind") != "retro":
        return False
    # Column and carried counts are structural facts the inputs already fix; a
    # result that disagrees would render a different board, not a slower one.
    columns = report.get("columns")
    if not isinstance(columns, list) or len(columns) != len(RETRO_GRIDS):
        return False
    carried = report.get("carried")
    return isinstance(carried, list) and len(carried) == len(inputs["report"].get("carried_action_items") or ())


def go_build_retro_export(inputs: dict) -> dict | None:
    """``retro.build_export`` served by the sidecar, or None → Python computes."""
    client = _client()
    if client is None:
        return None
    from yeaboi.gocore import CoreError

    try:
        result = client.request("retro.build_export", inputs)
    except CoreError as exc:
        logger.warning("gocore: retro.build_export failed (%s) — falling back to Python", exc)
        return None
    if not _valid_retro_export(result, inputs):
        logger.warning("gocore: retro.build_export result malformed — falling back to Python")
        return None
    logger.info("gocore: retro.build_export served by the sidecar")
    return result


def _client():
    """The discovered sidecar client, or None; never raises (an export must not sink)."""
    try:
        from yeaboi import gocore

        return gocore.get_client()
    except Exception as exc:  # noqa: BLE001 — dispatch must never sink an export
        logger.warning("gocore: client unavailable (%s: %s) — using the Python path", type(exc).__name__, exc)
        return None


def _export_doc(report: RetroReport, *, history: Sequence[dict] = (), editable: bool = False) -> dict:
    """One retro document — markdown + export args — sidecar-served when available."""
    inputs = build_retro_export_inputs(report, history=history, editable=editable)
    return go_build_retro_export(inputs) or build_retro_export(inputs)



def _md_section(title: str, items: tuple[str, ...], style: str = "bullets") -> list[str]:
    """A ``## title`` section; ``style`` picks bullets, ``numbered``, or ``tasks``.

    Numbered lists and checkbox task lists give published docs (Notion /
    Confluence) native variety — checkboxes become checkable task items.
    """
    if not items:
        return []
    if style == "numbered":
        body = [f"{i}. {it}" for i, it in enumerate(items, start=1)]
    elif style == "tasks":
        body = [f"- [ ] {it}" for it in items]
    else:
        body = [f"- {it}" for it in items]
    return [f"## {title}", ""] + body + [""]


def _md_table(headers: Sequence[str], rows: Sequence[Sequence[str]]) -> list[str]:
    """A pipe table, which Notion and Confluence both render natively.

    A table is the only Markdown structure that keeps a number beside its
    denominator: "12" in a bullet list is not the same fact as "12 of 14".
    """
    if not rows:
        return []
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join(" --- " for _ in headers) + "|"]
    out += ["| " + " | ".join(cell for cell in row) + " |" for row in rows]
    return out + [""]


def _md_measured(artifact) -> list[str]:
    """The measured numbers as a table. Absent metrics simply have no row.

    Never a dash and never a zero for a figure with no sample — a reader takes
    both for a measurement, and one of them for a bad one.
    """
    rows = []
    for metric in getattr(artifact, "metrics", ()) or ():
        if metric.denominator:
            value = f"{metric.value:g} of {metric.denominator:g}"
        else:
            value = f"{metric.value:g}{metric.unit}"
        rows.append((metric.label, value, EVIDENCE_SOURCE_LABELS.get(metric.source, metric.source)))
    if not rows:
        return []
    return ["## Measured", ""] + _md_table(("Metric", "Value", "Source"), rows)


def _md_evidence(artifact) -> list[str]:
    """The structured evidence rows, one bullet each, grouped by source.

    Nothing is folded or capped here the way the browser folds it: Markdown is
    the copy that outlives the tool, and evidence.py already bounds the volume.
    """
    groups = [g for g in getattr(artifact, "evidence_items", ()) or () if g.items]
    if not groups:
        return []
    lines = ["## Evidence", ""]
    for group in groups:
        lines += [f"### {group.label or group.source}", ""]
        for item in group.items:
            url = safe_url(item.url)
            # An unsafe scheme costs the link, never the row: the key is what the
            # reader is being shown evidence *of*.
            key = f"[{item.key}]({url})" if url and item.key else (item.key or "")
            where = " · ".join(bit for bit in (item.repository, item.status) if bit)
            head = " ".join(bit for bit in (f"[{item.kind}]" if item.kind else "", key, item.title) if bit)
            lines.append(f"- {head}" + (f" · {where}" if where else ""))
            for child in item.children:
                c_url = safe_url(child.url)
                c_key = f"[{child.key}]({c_url})" if c_url and child.key else (child.key or "")
                lines.append(f"  - {' '.join(bit for bit in (c_key, child.title) if bit)}")
        if group.note:
            lines.append(f"- _{group.note}_")
        lines.append("")
    return lines


def _md_footer() -> list[str]:
    ts = datetime.now().strftime("%Y-%m-%d %H:%M")
    return ["---", "", f"🤙 _Generated by [yeaboi.ai](https://yeaboi.ai) · {ts}_", ""]


def build_prep_markdown(prep: OneOnOnePrep) -> str:
    lines = [f"# 1:1 Prep — {prep.engineer}", "", f"_Prepared {prep.date}_", ""]
    if prep.activity_summary:
        # Quoted per line so multi-line summaries stay one blockquote.
        lines += ["## Sprint work", "", *(f"> {ln}" for ln in prep.activity_summary.splitlines()), ""]
    lines += _md_section("Carried-over action items", prep.carried_action_items, style="tasks")
    lines += _md_section("Talking points", prep.talking_points, style="numbered")
    lines += _md_section("Feedback to give", prep.feedback)
    lines += _md_section("Goals to align on", prep.goals)
    lines += _md_section("Gaps observed", prep.gaps)
    lines += _md_section("Areas to improve", prep.improvements)
    lines += _md_measured(prep)
    lines += _md_evidence(prep)
    lines += _md_section("Evidence coverage", coverage_lines(prep))
    lines += _md_section("⚠ Notices", prep.warnings)
    return "\n".join(lines + annotations_markdown(prep.annotations) + _md_footer())


def build_completion_markdown(record: OneOnOneRecord) -> str:
    lines = [f"# 1:1 Summary — {record.engineer}", "", f"_{record.date}_", ""]
    if record.email_subject:
        lines += [f"**Subject:** {record.email_subject}", ""]
    if record.email_summary:
        lines += ["## Summary email", "", record.email_summary, ""]
    lines += _md_section("Action items", record.action_items, style="tasks")
    lines += _md_section("Highlights", record.highlights)
    lines += _md_measured(record)
    lines += _md_evidence(record)
    lines += _md_section("Evidence coverage", coverage_lines(record))
    if record.evidence_date:
        lines += [f"_Numbers and evidence carried from the 1:1 prep of {record.evidence_date}._", ""]
    lines += _md_section("⚠ Notices", record.warnings)
    return "\n".join(lines + annotations_markdown(record.annotations) + _md_footer())


def build_review_markdown(review: SixMonthReview) -> str:
    lines = [
        f"# 6-Month Performance Review — {review.engineer}",
        "",
        f"_Period: {review.period_start} to {review.period_end}_",
        "",
    ]
    if review.overall:
        # Quoted per line so multi-line assessments stay one blockquote.
        lines += ["## Overall", "", *(f"> {ln}" for ln in review.overall.splitlines()), ""]
    lines += _md_section("Strengths", review.strengths)
    lines += _md_section("Achievements", review.achievements)
    lines += _md_section("Areas for improvement", review.areas_for_improvement)
    lines += _md_section("Goals for next period", review.goals, style="numbered")
    lines += _md_measured(review)
    lines += _md_evidence(review)
    lines += _md_section("Evidence coverage", coverage_lines(review))
    if review.framework_used:
        lines += [f"_Framework: {review.framework_used}_", ""]
    lines += _md_section("⚠ Notices", review.warnings)
    return "\n".join(lines + annotations_markdown(review.annotations) + _md_footer())



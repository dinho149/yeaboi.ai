def _section_id(title: str, seen: set[str]) -> str:
    """A stable anchor for a section heading, de-collided within one document.

    Slugged here rather than in the component so a table of contents and the
    heading it points at cannot disagree — two implementations of one rule is how
    a nav link ends up pointing at nothing.
    """
    base = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-") or "section"
    slug, n = base, 2
    while slug in seen:
        slug, n = f"{base}-{n}", n + 1
    seen.add(slug)
    return slug


def _stats_payload(artifact: object) -> list[dict[str, object]]:
    """Measured numbers for the browser: the figure and what it IS, never its colour.

    A metric with no sample never reaches here — evidence.py omits it — so the
    list carries no placeholder zeros for a reader to mistake for a finding.
    """
    rows: list[dict[str, object]] = []
    for metric in getattr(artifact, "metrics", ()) or ():
        row: dict[str, object] = {
            "id": metric.key,
            "label": metric.label,
            "value": metric.value,
            "unit": metric.unit,
            "source": metric.source,
            "group": metric.group,
        }
        if metric.denominator:
            row["of"] = metric.denominator
        if metric.detail:
            row["hint"] = metric.detail
        rows.append(row)
    return rows


def _coverage_payload(artifact: object) -> list[dict[str, str]]:
    """One row per evidence source: what was scanned, and what was not."""
    return [
        {"source": source, "state": state, "detail": detail}
        for source, state, detail in getattr(artifact, "evidence_coverage", ()) or ()
    ]


def _evidence_groups_payload(artifact: object) -> list[dict[str, object]]:
    """Structured evidence rows, grouped by the source that produced them."""
    return [
        {
            "source": group.source,
            "label": group.label,
            "items": evidence_payload(group.items),
            "note": group.note,
        }
        for group in getattr(artifact, "evidence_items", ()) or ()
        if group.items
    ]


def _perf_args(
    *,
    engineer: str,
    wordmark: str,
    title: str,
    subtitle: str,
    artifact_kind: str,
    sections: Sequence[tuple[str, Sequence[str], str]],
    lead: tuple[str, str] | None = None,
    period: tuple[str, str] | None = None,
    footnote: str = "",
    warnings: Sequence[str] = (),
    artifact: object = None,
    editable: bool = False,
    editable_fields: Sequence[str] = (),
    lead_field: str = "",
) -> dict[str, object]:
    """Build the chrome + payload arguments for any one of the three artifacts.

    One function for all three, because all three *are* one shape: an engineer,
    at most one block of free prose, then a list of titled bullet runs. The
    previous ``build_prep_html`` / ``build_completion_html`` / ``build_review_html``
    differed only in which section titles they passed — three copies of the same
    assembly, each with a Markdown twin differing the same way. The Markdown
    builders above still differ (numbered lists and task checkboxes are real
    distinctions there, and they publish to Notion / Confluence as native
    blocks); the HTML side had no such reason.

    Empty sections are dropped here rather than in the renderer so the payload
    carries no rows that draw nothing.
    """
    seen: set[str] = set()
    states = {s: (state, reason) for s, state, reason in getattr(artifact, "section_states", ()) or ()}

    def _section(name: str, items: Sequence[str], field: str) -> dict[str, object]:
        row: dict[str, object] = {"id": _section_id(name, seen), "title": name, "items": list(items)}
        state, reason = states.get(field, ("", ""))
        # Only an EMPTY section carries a state: a populated one explains itself,
        # and "covered" printed beside a list of findings is noise.
        if not items and state:
            row["state"] = state
            if reason:
                row["reason"] = reason
        return row

    report: dict[str, object] = {
        "kind": "performance",
        "engineer": engineer,
        "artifact": artifact_kind,
        # An empty section still rides when the engine knows why it is empty.
        # Dropping it is what made "found nothing" and "nobody looked" the same
        # silence; a section with neither items nor a state is still dropped.
        "sections": [_section(name, items, field) for name, items, field in sections if items or field in states],
        "stats": _stats_payload(artifact),
        "coverage": _coverage_payload(artifact),
        "evidence": _evidence_groups_payload(artifact),
        "warnings": list(warnings),
    }
    if period and any(period):
        report["period"] = {"start": period[0], "end": period[1]}
    if lead and lead[1]:
        # The lead block names the artifact field it came from when the
        # document is editable — three artifacts share this shape and each
        # calls its prose something different, so the component would
        # otherwise have to guess which key of `edit` belongs to it.
        report["lead"] = {"title": lead[0], "text": lead[1], **({"field": lead_field} if editable else {})}
    if footnote:
        report["footnote"] = footnote
    if editable and artifact is not None:
        report["edit"] = edit_map("", artifact, editable_fields)

    # A table of contents earns itself only on a document long enough to need
    # one; below three entries it is a second copy of the headings.
    nav = [(str(s["id"]), str(s["title"])) for s in report["sections"]]
    if report["evidence"]:
        nav.append(("evidence", "Evidence"))
    if report["coverage"]:
        nav.append(("coverage", "Coverage"))

    rows = sum(len(g["items"]) for g in report["evidence"])
    sources = getattr(artifact, "evidence_sources", ()) or ()
    facts = [
        ("SOURCES", ", ".join(EVIDENCE_SOURCE_LABELS.get(s, s) for s in sources)),
        ("EVIDENCE", f"{rows} item{'' if rows == 1 else 's'}" if rows else ""),
    ]

    args = dict(
        mode="performance",
        title=title,
        wordmark=wordmark,
        subtitle=subtitle,
        # No ENGINEER eyebrow: the title says the name and the body opens with
        # the avatar row, and a header that says "Ada Lovelace" three times in
        # 100 vertical pixels is not emphasis, it is noise. What these two say is
        # something the title cannot: what the document was built out of.
        facts=[(label, value) for label, value in facts if value],
        nav=nav if len(nav) >= 3 else [],
        report=report,
        footer=f"Generated by yeaboi.ai • {datetime.now().strftime('%Y-%m-%d')}",
    )
    return with_annotations(args, artifact)


def _perf_page(args: dict[str, object], *, markdown_name: str, document_title: str) -> str:
    """Wrap one artifact's payload arguments in a self-contained document."""
    from yeaboi.html_theme import export_page

    return export_page(**args, markdown_name=markdown_name, document_title=document_title)  # type: ignore[arg-type]


def prep_export_args(prep: OneOnOnePrep, *, editable: bool = False) -> dict[str, object]:
    """Chrome + payload arguments for a 1:1 prep."""
    return _perf_args(
        engineer=prep.engineer,
        wordmark="prep",
        title=f"1:1 Prep — {prep.engineer}",
        subtitle=f"Prepared {prep.date}",
        artifact_kind="prep",
        lead=("Sprint work", prep.activity_summary),
        sections=[
            ("Carried-over action items", prep.carried_action_items, "carried_action_items"),
            ("Talking points", prep.talking_points, "talking_points"),
            ("Feedback to give", prep.feedback, "feedback"),
            ("Goals to align on", prep.goals, "goals"),
            ("Gaps observed", prep.gaps, "gaps"),
            ("Areas to improve", prep.improvements, "improvements"),
        ],
        warnings=prep.warnings,
        artifact=prep,
        editable=editable,
        lead_field="activity_summary",
        editable_fields=("activity_summary",),
    )


def build_prep_html(prep: OneOnOnePrep, *, markdown_name: str = "", document_title: str = "") -> str:
    return _perf_page(prep_export_args(prep), markdown_name=markdown_name, document_title=document_title)


def completion_export_args(record: OneOnOneRecord, *, editable: bool = False) -> dict[str, object]:
    """Chrome + payload arguments for a completed 1:1."""
    return _perf_args(
        engineer=record.engineer,
        wordmark="summary",
        title=f"1:1 Summary — {record.engineer}",
        subtitle=record.date,
        artifact_kind="completion",
        lead=("Summary email", record.email_summary),
        sections=[
            # The subject is one line and belongs with the email it titles, but
            # it is not a bullet run, so it rides as a one-item section rather
            # than growing a second free-prose slot used by one artifact.
            ("Subject", (record.email_subject,) if record.email_subject else (), "email_subject"),
            ("Action items", record.action_items, "action_items"),
            ("Highlights", record.highlights, "highlights"),
        ],
        warnings=record.warnings,
        # A completion's numbers and evidence rows were gathered for its prep, on
        # a different day. Saying which day is the difference between evidence and
        # an assertion — this document is the one the engineer receives.
        footnote=(
            f"Numbers and evidence carried from the 1:1 prep of {record.evidence_date}." if record.evidence_date else ""
        ),
        artifact=record,
        editable=editable,
        lead_field="email_summary",
        editable_fields=("email_subject", "email_summary"),
    )


def build_completion_html(record: OneOnOneRecord, *, markdown_name: str = "", document_title: str = "") -> str:
    return _perf_page(completion_export_args(record), markdown_name=markdown_name, document_title=document_title)


def review_export_args(review: SixMonthReview, *, editable: bool = False) -> dict[str, object]:
    """Chrome + payload arguments for a six-month review."""
    return _perf_args(
        engineer=review.engineer,
        wordmark="review",
        title=f"6-Month Review — {review.engineer}",
        subtitle=f"Period: {review.period_start} to {review.period_end}",
        artifact_kind="review",
        lead=("Overall", review.overall),
        period=(review.period_start, review.period_end),
        sections=[
            ("Strengths", review.strengths, "strengths"),
            ("Achievements", review.achievements, "achievements"),
            ("Areas for improvement", review.areas_for_improvement, "areas_for_improvement"),
            ("Goals for next period", review.goals, "goals"),
        ],
        footnote=f"Framework: {review.framework_used}" if review.framework_used else "",
        warnings=review.warnings,
        artifact=review,
        editable=editable,
        lead_field="overall",
        editable_fields=("overall",),
    )


def build_review_html(review: SixMonthReview, *, markdown_name: str = "", document_title: str = "") -> str:
    return _perf_page(review_export_args(review), markdown_name=markdown_name, document_title=document_title)



# Markdown
# ---------------------------------------------------------------------------


def build_poker_markdown(report: PokerReport, *, generated_ts: str = "") -> str:
    """Return the poker session as a Markdown document.

    ``generated_ts`` pins the footer timestamp; empty means "now". The seam
    hoists it into :func:`build_poker_export_inputs` so the sidecar and the
    reference implementation render the same bytes from the same document.
    """
    from yeaboi.markdown_convert import md_table_cell as _cell

    estimated = sum(1 for t in report.tickets if t.estimated)
    lines: list[str] = [
        f"# {_title(report)}",
        "",
        f"**Date:** {report.date}  ",
        f"**Source:** {report.source or '—'} · {report.scope_label or '—'}  ",
        f"**Estimated:** {estimated}/{len(report.tickets)} tickets  ",
        f"**Participants:** {', '.join(report.participants) if report.participants else '—'}",
        "",
        "| Ticket | Summary | Before | Final | Votes |",
        "|--------|---------|--------|-------|-------|",
    ]
    for t in report.tickets:
        # safe_url: tracker URLs are attacker-influenced, and a Markdown link
        # becomes an <a href> downstream (Notion/Confluence/GitHub).
        key = f"[{t.key}]({safe})" if (safe := safe_url(t.url)) else t.key
        final = _pts(t.final_points) if t.estimated else "_skipped_"
        votes = _votes_str(t) or "—"
        lines.append(f"| {key} | {_cell(t.summary)} | {_pts(t.initial_points)} | {final} | {_cell(votes)} |")
    lines.append("")

    ai_notes = [(t.key, t.ai_note) for t in report.tickets if t.ai_note]
    if ai_notes:
        lines += ["## AI perspectives", ""]
        for key, note in ai_notes:
            lines.append(f"- **{key}** — {_cell(note)}")
        lines.append("")

    duels = [t for t in report.tickets if t.duel_transcript]
    if duels:
        lines += ["## Duels", ""]
        for t in duels:
            lines.append(f"**{t.key}** — {t.duel_low} vs {t.duel_high}")
            lines.append("")
            lines += [f"> {line}" for line in t.duel_transcript.splitlines()]
            lines.append("")

    ts = generated_ts or datetime.now().strftime("%Y-%m-%d %H:%M")
    lines += ["---", "", f"🤙 _Generated by [yeaboi.ai](https://yeaboi.ai) · {ts}_", ""]
    return "\n".join(lines)



# The build-export seam — poker.build_export
# ---------------------------------------------------------------------------


def build_poker_export_inputs(report: PokerReport, *, history: Sequence[dict] = ()) -> dict:
    """Freeze one poker document into the ``poker.build_export`` wire params.

    A single ``datetime.now()`` capture hoists the seam's only nondeterminism
    into the params, and the json round-trip freezes the report into the same
    plain-JSON shape a stored one takes — so the sidecar and the reference
    implementation see byte-identical inputs.
    """
    now = datetime.now()
    return json.loads(
        json.dumps(
            {
                "report": asdict(report),
                "history": list(history),
                "generated_ts": now.strftime("%Y-%m-%d %H:%M"),
                "generated_date": now.strftime("%Y-%m-%d"),
            }
        )
    )


def build_poker_export(inputs: dict) -> dict:
    """Python reference implementation of ``poker.build_export``.

    Rebuilds the report through the store deserializer — the same round-trip a
    stored report takes — then renders with the wire-pinned timestamps. Key
    order is contractual: ``args`` is json.dumps-ed into the page boot payload.
    """
    from yeaboi.gocore.client import CONTRACT_VERSION
    from yeaboi.poker.store import report_from_dict

    report = report_from_dict(inputs["report"])
    return {
        "contract_version": CONTRACT_VERSION,
        "markdown": build_poker_markdown(report, generated_ts=inputs["generated_ts"]),
        "args": poker_export_args(report, history=inputs["history"], generated_date=inputs["generated_date"]),
    }


def _valid_poker_export(result: object, inputs: dict) -> bool:
    """Structural checks on a sidecar result — any failure means malformed → Python."""
    if not isinstance(result, dict):
        return False
    if not (isinstance(result.get("markdown"), str) and result["markdown"]):
        return False
    args = result.get("args")
    if not isinstance(args, dict):
        return False
    report = args.get("report")
    if not isinstance(report, dict) or report.get("kind") != "poker":
        return False
    # The ticket count is a structural fact the inputs already fix; a result
    # that disagrees would render a different session, not a slower one.
    tickets = report.get("tickets")
    return isinstance(tickets, list) and len(tickets) == len(inputs["report"].get("tickets") or ())


def go_build_poker_export(inputs: dict) -> dict | None:
    """``poker.build_export`` served by the sidecar, or None → Python computes."""
    client = _client()
    if client is None:
        return None
    from yeaboi.gocore import CoreError

    try:
        result = client.request("poker.build_export", inputs)
    except CoreError as exc:
        logger.warning("gocore: poker.build_export failed (%s) — falling back to Python", exc)
        return None
    if not _valid_poker_export(result, inputs):
        logger.warning("gocore: poker.build_export result malformed — falling back to Python")
        return None
    logger.info("gocore: poker.build_export served by the sidecar")
    return result


def _client():
    """The discovered sidecar client, or None; never raises (an export must not sink)."""
    try:
        from yeaboi import gocore

        return gocore.get_client()
    except Exception as exc:  # noqa: BLE001 — dispatch must never sink an export
        logger.warning("gocore: client unavailable (%s: %s) — using the Python path", type(exc).__name__, exc)
        return None


def _export_doc(report: PokerReport, *, history: Sequence[dict] = ()) -> dict:
    """One poker document — markdown + export args — sidecar-served when available."""
    inputs = build_poker_export_inputs(report, history=history)
    return go_build_poker_export(inputs) or build_poker_export(inputs)


